"""
Spec-to-PBT Generator

Parses OpenSpec markdown specs and generates property-based tests using Hypothesis.
Extracts properties from function_contract clauses and generates PBT test code.
"""

import re
import yaml
from pathlib import Path
from typing import List, Dict, Any
import textwrap


class PropertyExtractor:
    """Extracts testable properties from OpenSpec markdown."""
    
    def __init__(self, spec_path: Path):
        self.spec_path = spec_path
        self.spec_text = spec_path.read_text()
        self.spec_id = spec_path.parent.name
        
    def extract_properties(self) -> List[Dict[str, Any]]:
        """Extract all function_contract clauses that can be turned into PBT tests."""
        properties = []
        
        # Find all YAML clause blocks
        clause_pattern = r'```yaml clause\n(.*?)\n```'
        clauses = re.findall(clause_pattern, self.spec_text, re.DOTALL)
        
        for clause_text in clauses:
            try:
                clause = yaml.safe_load(clause_text)
                if clause.get('use') == 'function_contract':
                    properties.append(self._parse_function_contract(clause))
                elif clause.get('use') == 'always_on_calls':
                    properties.append(self._parse_always_on_calls(clause))
                elif clause.get('use') == 'setting_in_range':
                    properties.append(self._parse_setting_in_range(clause))
            except Exception as e:
                print(f"Warning: Could not parse clause: {e}")
                continue
        
        return properties
    
    def _parse_function_contract(self, clause: Dict) -> Dict[str, Any]:
        """Parse a function_contract clause into a property definition."""
        with_data = clause['with']
        function_ref = with_data['function']
        
        # Parse function reference: "services/workflow.py::review_age_ok"
        if '::' in function_ref:
            file_path, function_name = function_ref.split('::')
        else:
            file_path = None
            function_name = function_ref
        
        return {
            'type': 'function_contract',
            'function': function_name,
            'file': file_path,
            'inputs': with_data.get('inputs', {}),
            'assume': with_data.get('assume'),
            'ensures': with_data.get('ensures'),
            'examples': with_data.get('examples', 100),
            'rung': clause.get('require', 'L3')
        }
    
    def _parse_always_on_calls(self, clause: Dict) -> Dict[str, Any]:
        """Parse an always_on_calls clause into a property definition."""
        with_data = clause['with']
        return {
            'type': 'always_on_calls',
            'tools': with_data['tools'],
            'condition': with_data.get('where'),
        }
    
    def _parse_setting_in_range(self, clause: Dict) -> Dict[str, Any]:
        """Parse a setting_in_range clause into a property definition."""
        with_data = clause['with']
        return {
            'type': 'setting_in_range',
            'key': with_data['key'],
            'min': with_data.get('min'),
            'max': with_data.get('max'),
            'value': with_data.get('value'),
        }


class PBTGenerator:
    """Generates Hypothesis property-based test code from extracted properties."""
    
    def __init__(self, spec_id: str):
        self.spec_id = spec_id
        
    def generate_test_file(self, properties: List[Dict[str, Any]]) -> str:
        """Generate a complete Python test file with all properties."""
        
        tests = []
        imports = set([
            "from hypothesis import given, strategies as st, settings, assume",
            "import pytest",
        ])
        
        for i, prop in enumerate(properties, 1):
            if prop['type'] == 'function_contract':
                test_code, test_imports = self._generate_function_contract_test(prop, i)
                tests.append(test_code)
                imports.update(test_imports)
            elif prop['type'] == 'always_on_calls':
                test_code, test_imports = self._generate_always_on_calls_test(prop, i)
                tests.append(test_code)
                imports.update(test_imports)
            elif prop['type'] == 'setting_in_range':
                test_code, test_imports = self._generate_setting_test(prop, i)
                tests.append(test_code)
                imports.update(test_imports)
        
        header = f'''"""
Property-based tests auto-generated from spec {self.spec_id}

Generated by spec_to_pbt.py
"""

{chr(10).join(sorted(imports))}


'''
        
        return header + "\n\n".join(tests)
    
    def _generate_function_contract_test(self, prop: Dict, index: int) -> tuple:
        """Generate a PBT test for a function contract."""
        
        function_name = prop['function']
        inputs = prop['inputs']
        assume_expr = prop['assume']
        ensures_expr = prop['ensures']
        examples = prop['examples']
        
        # Generate hypothesis strategies for each input
        strategies = []
        for param, param_type in inputs.items():
            if param_type == 'int':
                strategies.append(f"    {param}=st.integers(min_value=-1000, max_value=1000),")
            elif param_type == 'float':
                strategies.append(f"    {param}=st.floats(allow_nan=False, allow_infinity=False),")
            elif param_type == 'str':
                strategies.append(f"    {param}=st.text(),")
            elif param_type == 'bool':
                strategies.append(f"    {param}=st.booleans(),")
        
        param_names = list(inputs.keys())
        param_str = ", ".join(param_names)
        
        # Import the function
        if prop['file']:
            module_path = prop['file'].replace('/', '.').replace('.py', '')
            import_stmt = f"from traceeval.sut.{module_path} import {function_name}"
        else:
            import_stmt = f"# TODO: Import {function_name}"
        
        test_code = f'''@given(
{chr(10).join(strategies)}
)
@settings(max_examples={examples})
def test_{function_name}_property_{index}({param_str}):
    """
    Property from spec: {prop['ensures']}
    
    Precondition: {prop['assume'] or 'none'}
    Postcondition: {ensures_expr}
    """
    # Apply precondition
    {f"assume({assume_expr})" if assume_expr else "pass"}
    
    # Call the function
    result = {function_name}({param_str})
    
    # Check the postcondition
    assert {ensures_expr}, \\
        f"Property violated with inputs: {param_str}, result={{result}}"
'''
        
        return test_code, {import_stmt}
    
    def _generate_always_on_calls_test(self, prop: Dict, index: int) -> tuple:
        """Generate a test that checks a condition holds on all tool calls."""
        
        tools = prop['tools']
        condition = prop['condition']
        
        test_code = f'''def test_always_on_calls_property_{index}():
    """
    Property: On every call to {tools}, the condition holds:
    {condition}
    
    This requires runtime trace analysis - see test implementation.
    """
    # TODO: Implement trace-based property check
    # This would:
    # 1. Run catalog cases
    # 2. Extract all {tools} events from audit
    # 3. Verify condition for each event
    pytest.skip("Requires trace analysis infrastructure")
'''
        
        return test_code, set()
    
    def _generate_setting_test(self, prop: Dict, index: int) -> tuple:
        """Generate a test that checks configuration constraints."""
        
        key = prop['key']
        min_val = prop.get('min')
        max_val = prop.get('max')
        expected_val = prop.get('value')
        
        test_code = f'''def test_setting_{key.replace(".", "_")}():
    """
    Property: Configuration setting {key} must be in range [{min_val}, {max_val}]
    {f"Expected value: {expected_val}" if expected_val else ""}
    """
    from traceeval.sut.harness.config import load_config
    
    config = load_config()
    value = config
    for part in "{key}".split("."):
        value = value[part]
    
    assert isinstance(value, int), f"{{value}} is not an integer"
    {f"assert {min_val} <= value <= {max_val}, f'{{value}} not in range [{min_val}, {max_val}]'" if min_val and max_val else ""}
    {f"assert value == {expected_val}, f'Expected {expected_val}, got {{value}}'" if expected_val else ""}
'''
        
        return test_code, set()


def generate_pbt_from_spec(spec_path: Path, output_path: Path = None):
    """Main entry point: generate PBT tests from a spec file."""
    
    extractor = PropertyExtractor(spec_path)
    properties = extractor.extract_properties()
    
    if not properties:
        print(f"No testable properties found in {spec_path}")
        return None
    
    generator = PBTGenerator(extractor.spec_id)
    test_code = generator.generate_test_file(properties)
    
    if output_path is None:
        output_path = Path(f"test_pbt_{extractor.spec_id}.py")
    
    output_path.write_text(test_code)
    print(f"Generated {len(properties)} property tests → {output_path}")
    
    return output_path


if __name__ == "__main__":
    import sys
    
    if len(sys.argv) < 2:
        print("Usage: python spec_to_pbt.py <spec.md> [output.py]")
        print("\nExample:")
        print("  python spec_to_pbt.py openspec/specs/fs-0101-approval-validity/spec.md")
        sys.exit(1)
    
    spec_path = Path(sys.argv[1])
    output_path = Path(sys.argv[2]) if len(sys.argv) > 2 else None
    
    generate_pbt_from_spec(spec_path, output_path)
